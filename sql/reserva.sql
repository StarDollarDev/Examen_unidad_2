CREATE TABLE reserva (
    idreserva      NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
    cliente        VARCHAR2(100)  NOT NULL,
    servicio       VARCHAR2(100)  NOT NULL,
    cantidad       NUMBER(5)      NOT NULL,
    precio         NUMBER(10,2)   NOT NULL,
    subtotal       NUMBER(12,2)   NOT NULL,
    total          NUMBER(12,2)   NOT NULL,
    fecha_reserva  DATE           DEFAULT SYSDATE NOT NULL,
    estado         VARCHAR2(20)   DEFAULT 'PENDIENTE' NOT NULL,
    CONSTRAINT pk_reserva          PRIMARY KEY (idreserva),
    CONSTRAINT ck_reserva_cantidad CHECK (cantidad > 0),
    CONSTRAINT ck_reserva_precio   CHECK (precio >= 0),
    CONSTRAINT ck_reserva_estado   CHECK (estado IN ('PENDIENTE','CONFIRMADA','CANCELADA'))
);

COMMENT ON TABLE  reserva               IS 'Registro de reservas';
COMMENT ON COLUMN reserva.idreserva     IS 'Clave primaria autoincremental';
COMMENT ON COLUMN reserva.subtotal      IS 'cantidad * precio';
COMMENT ON COLUMN reserva.total         IS 'subtotal + IGV (18%)';

